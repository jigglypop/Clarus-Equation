def _first_moment_exponential_kernel(
    frequency_bar: float,
    interval_bar: float,
) -> complex:
    '''Return integral_0^T t exp(i omega t) dt with a stable zero limit.'''

    omega = float(frequency_bar)
    interval = float(interval_bar)
    argument = omega * interval
    if abs(argument) <= 1.0e-4:
        total = 0.0j
        factorial = 1.0
        power = 1.0 + 0.0j
        for order in range(12):
            if order > 0:
                factorial *= order
                power *= 1j * omega
            total += power * interval ** (order + 2) / (
                factorial * (order + 2)
            )
        return complex(total)
    return complex(
        (np.exp(1j * argument) * (1.0 - 1j * argument) - 1.0)
        / omega**2
    )


def finite_time_ordered_double_kernel(
    later_frequency_bar: float,
    earlier_frequency_bar: float,
    interval_bar: float,
) -> complex:
    '''Return integral_0^T dt2 e^(i x t2) integral_0^t2 dt1 e^(i y t1).'''

    later = float(later_frequency_bar)
    earlier = float(earlier_frequency_bar)
    interval = float(interval_bar)
    if (
        not np.isfinite(later)
        or not np.isfinite(earlier)
        or not np.isfinite(interval)
        or interval <= 0.0
    ):
        raise ValueError('the ordered kernel requires finite frequencies and T>0')
    if abs(earlier * interval) <= 1.0e-7:
        return _first_moment_exponential_kernel(later, interval)
    return complex(
        (
            finite_time_exponential_kernel(later + earlier, interval)
            - finite_time_exponential_kernel(later, interval)
        )
        / (1j * earlier)
    )


def simpson_ordered_double_kernel(
    later_frequency_bar: float,
    earlier_frequency_bar: float,
    interval_bar: float,
    *,
    subintervals: int,
    block_rows: int = 256,
) -> complex:
    '''Independently integrate the ordered triangle via a unit-square map.'''

    if (
        not isinstance(subintervals, int)
        or subintervals < 2
        or subintervals % 2
    ):
        raise ValueError('the ordered Simpson grid must be a positive even integer')
    if not isinstance(block_rows, int) or block_rows < 1:
        raise ValueError('the ordered Simpson block size must be positive')
    interval = float(interval_bar)
    if not np.isfinite(interval) or interval <= 0.0:
        raise ValueError('the ordered Simpson interval must be positive')
    count = subintervals
    unit = np.linspace(0.0, 1.0, count + 1)
    weights = np.ones(count + 1)
    weights[1:-1:2] = 4.0
    weights[2:-1:2] = 2.0
    inner_scale = 1.0 / (3.0 * count)
    outer_total = 0.0j
    for start in range(0, count + 1, block_rows):
        stop = min(count + 1, start + block_rows)
        outer = unit[start:stop]
        phases = np.exp(
            1j
            * float(later_frequency_bar)
            * interval
            * outer[:, None]
            + 1j
            * float(earlier_frequency_bar)
            * interval
            * outer[:, None]
            * unit[None, :]
        )
        inner = inner_scale * (phases @ weights)
        outer_total += np.sum(
            weights[start:stop] * interval**2 * outer * inner
        )
    return complex(outer_total / (3.0 * count))


def simpson_time_ordered_square_kernel(
    later_frequency_bar: float,
    earlier_frequency_bar: float,
    interval_bar: float,
    *,
    subintervals: int,
    block_rows: int = 256,
) -> complex:
    '''Return a Richardson-improved direct two-theta square integral.'''

    if (
        not isinstance(subintervals, int)
        or subintervals < 2
        or subintervals % 2
    ):
        raise ValueError('the square Simpson grid must be a positive even integer')
    if not isinstance(block_rows, int) or block_rows < 1:
        raise ValueError('the square Simpson block size must be positive')
    interval = float(interval_bar)
    if not np.isfinite(interval) or interval <= 0.0:
        raise ValueError('the square Simpson interval must be positive')

    def direct_square(count: int) -> complex:
        unit = np.linspace(0.0, 1.0, count + 1)
        weights = np.ones(count + 1)
        weights[1:-1:2] = 4.0
        weights[2:-1:2] = 2.0
        total = 0.0j
        for start in range(0, count + 1, block_rows):
            stop = min(count + 1, start + block_rows)
            first = unit[start:stop, None]
            second = unit[None, :]
            first_is_later = first >= second
            phase = np.where(
                first_is_later,
                np.exp(
                    1j
                    * interval
                    * (
                        float(later_frequency_bar) * first
                        + float(earlier_frequency_bar) * second
                    )
                ),
                np.exp(
                    1j
                    * interval
                    * (
                        float(later_frequency_bar) * second
                        + float(earlier_frequency_bar) * first
                    )
                ),
            )
            total += np.sum(
                weights[start:stop, None] * weights[None, :] * phase
            )
        return complex(0.5 * interval**2 * total / (9.0 * count**2))

    coarse = direct_square(subintervals)
    fine = direct_square(2 * subintervals)
    # The theta-boundary derivative kink leaves an O(h^2) diagonal error.
    return complex((4.0 * fine - coarse) / 3.0)


def simpson_time_ordered_square_kernel_with_stability(
    later_frequency_bar: float,
    earlier_frequency_bar: float,
    interval_bar: float,
    *,
    subintervals: int,
    block_rows: int = 256,
) -> tuple[complex, float]:
    '''Return the refined square result and its N-to-2N stability.'''

    first = simpson_time_ordered_square_kernel(
        later_frequency_bar,
        earlier_frequency_bar,
        interval_bar,
        subintervals=subintervals,
        block_rows=block_rows,
    )
    second = simpson_time_ordered_square_kernel(
        later_frequency_bar,
        earlier_frequency_bar,
        interval_bar,
        subintervals=2 * subintervals,
        block_rows=block_rows,
    )
    return complex(second), float(abs(second - first))


def select_certified_resonant_matrix_element(
    key: tuple[int, int, int],
    raw_matrix_element: complex,
    certificates: Mapping[tuple[int, int, int], ResonanceCertificate],
    *,
    relative_tolerance: float = 1.0e-10,
    absolute_tolerance: float = 1.0e-12,
) -> complex:
    '''Apply only a matching, branch-keyed resonance disposition.'''

    certificate = certificates.get(key)
    if certificate is None:
        raise ValueError(f'missing resonance certificate for channel {key}')
    if not np.isclose(
        raw_matrix_element,
        certificate.production_matrix_element,
        rtol=relative_tolerance,
        atol=absolute_tolerance,
    ):
        raise ValueError(
            f'resonance certificate does not match channel {key} matrix element'
        )
    if certificate.disposition == 'null':
        return 0.0j
    if (
        certificate.disposition == 'resolved'
        and certificate.local_exchange_elimination_rejected
    ):
        return complex(raw_matrix_element)
    raise ValueError(f'unclassified resonant channel {key}')


def _exact_star_survival_amplitude(
    initial_energy: float,
    intermediate_energies: tuple[float, ...],
    matrix_elements: tuple[complex, ...],
    contact: float,
    interval_bar: float,
    coupling: float,
) -> tuple[complex, float]:
    '''Return the interaction-picture survival amplitude of the Hermitian star.'''

    dimension = 1 + len(intermediate_energies)
    hamiltonian = np.zeros((dimension, dimension), dtype=complex)
    hamiltonian[0, 0] = initial_energy + coupling**2 * contact
    for index, (energy, matrix_element) in enumerate(
        zip(intermediate_energies, matrix_elements, strict=True),
        start=1,
    ):
        hamiltonian[index, index] = energy
        hamiltonian[index, 0] = coupling * matrix_element
        hamiltonian[0, index] = coupling * matrix_element.conjugate()
    hermiticity = float(np.linalg.norm(hamiltonian - hamiltonian.conj().T))
    eigenvalues, eigenvectors = np.linalg.eigh(hamiltonian)
    evolution = (
        eigenvectors
        @ np.diag(np.exp(-1j * eigenvalues * interval_bar))
        @ eigenvectors.conj().T
    )
    interaction = np.exp(1j * initial_energy * interval_bar) * evolution[0, 0]
    return complex(interaction), hermiticity


