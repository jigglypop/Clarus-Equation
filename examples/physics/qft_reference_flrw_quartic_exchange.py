class ScalarQuarticExchangeReceipt:
    base_wavenumber_bar: float
    branches: tuple[ScalarQuarticExchangeBranch, ...]
    maximum_cubic_step_residual: float
    maximum_cubic_grid_residual: float
    maximum_cubic_gauge_residual: float
