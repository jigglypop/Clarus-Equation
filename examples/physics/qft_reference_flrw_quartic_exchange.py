    intermediate_channel_keys: tuple[tuple[int, int, int], ...]
    intermediate_resonance_dispositions: tuple[str, ...]
    intermediate_raw_matrix_element_magnitudes: tuple[float, ...]
    contact_matrix_element: float
    intermediate_matrix_element_magnitudes: tuple[float, float]
    energy_mismatches_bar: tuple[float, float]
    resonant_null_channel_count: int
    discarded_raw_resonant_magnitude: float
    contact_coefficient_real: float
    contact_coefficient_imag: float
